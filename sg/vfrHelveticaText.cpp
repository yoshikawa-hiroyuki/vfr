vfrHelveticaText::vfrHelveticaText(const std::string& nm, const Bool ssm)
 : vfrLetters(nm, ssm)
{
  reset();
}

vfrHelveticaText::~vfrHelveticaText() {
}

void
vfrHelveticaText::reset() {
  setFontScale(1.0f);
}

void
vfrHelveticaText::generateBbox() {
  float tw = getTextWidth();
  _bbox[0][0] = 0.f;
  _bbox[1][0] = tw * _fontScale;
  if ( _alignType == AL_CENTER ) {
    _bbox[0][0] -= 0.5f * tw * _fontScale;
    _bbox[1][0] -= 0.5f * tw * _fontScale;
  } else if ( _alignType == AL_RIGHT ) {
    _bbox[0][0] -= tw * _fontScale;
    _bbox[1][0] -= tw * _fontScale;
  }

  _bbox[0][1] = -getTextHeight() * _fontScale * (getNumLines() - 0.5f);
  _bbox[1][1] = getTextHeight() * _fontScale * 0.5f;

  _bbox[0][2] = _bbox[1][2] = 0.f;
}

GLfloat
vfrHelveticaText::getTextWidth() const {
  register float tw = 0.f;
  register float maxw = 0.f;
  register int textLen = _textBuf.size();
  for ( register int i = 0; i < textLen; i++ ) {
    register GLint mode;
    if ( _textBuf[i] == '\n' ) {
      if ( tw > maxw ) maxw = tw;
      tw = 0.f;
      continue;
    }
    for ( register int j = 1; mode = helvFont[_textBuf[i]-32][j]; j += 3 )
      if ( mode == FONT_ADVANCE ) {
        tw += (float)helvFont[_textBuf[i]-32][j+1]*FILLED_SCALE;
        tw += _fontSize[0] * _spaceRate;
      }
  } // end of for(i)
  if ( tw > maxw ) maxw = tw;
  return maxw;
}

GLfloat
vfrHelveticaText::getTextHeight() const {
  return _fontSize[1];
}

GLfloat
vfrHelveticaText::drawLetter(const char c) const {
  if ( c < 0x20 || c > 0x7e )
    return 0.f;
  register int i = c - 0x20;
  register GLint mode;
  GLfloat retv = 0.f;
  for ( register int j = 1; mode = helvFont[i][j]; j += 3 ) {
    if ( mode == FONT_BEGIN ) {
      glBegin(GL_TRIANGLE_STRIP);
      glVertex3f((float)helvFont[i][j+1]*FILLED_SCALE,
                 (float)helvFont[i][j+2]*FILLED_SCALE, 0.f);
    } else if ( mode == FONT_NEXT ) {
      glVertex3f((float)helvFont[i][j+1]*FILLED_SCALE,
                 (float)helvFont[i][j+2]*FILLED_SCALE, 0.f);
    } else if ( mode == FONT_END ) {
      glVertex3f((float)helvFont[i][j+1]*FILLED_SCALE,
                 (float)helvFont[i][j+2]*FILLED_SCALE, 0.f);
      glEnd();
    } else if ( mode == FONT_ADVANCE ) {
      retv = (float)helvFont[i][j+1]*FILLED_SCALE +(_fontSize[0]*_spaceRate);
      glTranslatef(retv, (float)helvFont[i][j+2]*FILLED_SCALE, 0.f);
      break;
    }
  }
  return retv;
}

